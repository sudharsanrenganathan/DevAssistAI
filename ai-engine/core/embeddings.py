"""Text embeddings for Secret AI RAG.

Embeddings are generated by the Supabase ``gte-small`` edge function (see
``supabase/functions/embed``), so no ML libraries run inside this 512MB engine.
Only the standard ``requests`` dependency is used.

Config (environment):
- ``EMBEDDING_EDGE_URL`` — full function URL. If unset, derived from
  ``SUPABASE_URL`` as ``<SUPABASE_URL>/functions/v1/embed``.
- ``EMBEDDING_EDGE_KEY`` — bearer key; falls back to ``SUPABASE_ANON_KEY`` then
  ``SUPABASE_SERVICE_ROLE_KEY``.
"""
import os

import requests

EMBEDDING_DIM = 384
_TIMEOUT = 30


def _edge_url() -> str:
    url = os.getenv("EMBEDDING_EDGE_URL")
    if url:
        return url
    base = os.getenv("SUPABASE_URL", "").rstrip("/")
    if base:
        return f"{base}/functions/v1/embed"
    raise RuntimeError("EMBEDDING_EDGE_URL (or SUPABASE_URL) is not configured")


def _edge_key() -> str:
    key = (os.getenv("EMBEDDING_EDGE_KEY")
           or os.getenv("SUPABASE_ANON_KEY")
           or os.getenv("SUPABASE_SERVICE_ROLE_KEY"))
    if not key:
        raise RuntimeError(
            "No Supabase key for embeddings "
            "(set EMBEDDING_EDGE_KEY or SUPABASE_ANON_KEY)"
        )
    return key


def embed_texts(texts, input_type: str = "passage") -> list[list[float]]:
    """Embed a list of strings into 384-dim vectors via the gte-small edge fn.

    ``input_type`` is accepted for API symmetry with asymmetric models; gte-small
    is symmetric, so it is currently a no-op. Returns a list aligned with
    ``texts``. Raises on transport or shape errors (callers fail-open to the
    full-text fallback).
    """
    if not texts:
        return []
    if isinstance(texts, str):
        texts = [texts]

    resp = requests.post(
        _edge_url(),
        headers={
            "Authorization": f"Bearer {_edge_key()}",
            "Content-Type": "application/json",
        },
        json={"input": texts},
        timeout=_TIMEOUT,
    )
    resp.raise_for_status()
    data = resp.json()
    embeddings = data.get("embeddings") if isinstance(data, dict) else None
    if not isinstance(embeddings, list) or len(embeddings) != len(texts):
        raise RuntimeError(f"Unexpected embedding response: {str(data)[:200]}")
    return embeddings


def embed_query(text: str, input_type: str = "query") -> list[float]:
    """Embed a single query string; returns one 384-dim vector."""
    return embed_texts([text], input_type=input_type)[0]
