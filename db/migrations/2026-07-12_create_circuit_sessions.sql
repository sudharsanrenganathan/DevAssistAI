-- Migration: per-user persistence for Circuit sessions (2026-07-12).
-- One row = one "circuit" — a whole board session (a collection of
-- sub-circuits plus its chat transcript). Users can reopen a session after
-- login and continue asking, or delete it; a new session starts only when
-- they press "New question". Read/written by the Spring Boot backend (JPA)
-- over SPRING_DATASOURCE_URL. payload holds JSON serialized as text (switch
-- to jsonb later with ALTER ... TYPE jsonb USING ...::jsonb if needed).

create table if not exists public.circuit_sessions (
    id          bigint generated by default as identity primary key,
    user_email  text        not null,
    title       text        not null,
    payload     text        not null default '{}', -- {circuits:[...], convo:[...]}
    sub_count   integer     not null default 0,    -- number of sub-circuits on the board
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

create index if not exists idx_circuit_sessions_user
    on public.circuit_sessions (user_email, updated_at desc);

-- RLS on with no policies: PostgREST roles can't touch it; the backend
-- connects as the table owner, which bypasses RLS.
alter table public.circuit_sessions enable row level security;

comment on table public.circuit_sessions is
    'Saved Circuit board sessions (collections of sub-circuits), one row per session, owned by user_email.';
