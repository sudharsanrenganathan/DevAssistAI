-- Migration: per-user persistence for Ignite (project builder) projects
-- (2026-07-06). Projects previously lived only in browser memory; now every
-- plan/file/edit is auto-saved so a user whose daily token quota runs out can
-- log in tomorrow, reopen the project, and resume generating the missing files.
-- Read/written by the Spring Boot backend (JPA) over SPRING_DATASOURCE_URL.
-- plan/files hold JSON serialized as text (switch to jsonb later with
-- ALTER ... TYPE jsonb USING ...::jsonb if in-database querying is needed).

create table if not exists public.ignite_projects (
    id          bigint generated by default as identity primary key,
    user_email  text        not null,
    name        text        not null,
    slug        text,
    summary     text,
    prompt      text,
    plan        text,                              -- plan JSON: {project:{...}, files:[{path,description}]}
    files       text        not null default '{}', -- files JSON: {path: content} (done files only)
    status      text        not null default 'generating',  -- generating | complete
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

create index if not exists idx_ignite_projects_user
    on public.ignite_projects (user_email, updated_at desc);

-- RLS on with no policies: PostgREST roles can't touch it; the backend
-- connects as the table owner, which bypasses RLS.
alter table public.ignite_projects enable row level security;

comment on table public.ignite_projects is
    'Saved Ignite (project builder) projects, one row per project, owned by user_email.';
